// The assistant's service boundary. Screens call `askAssistant`; which provider answers is
// decided here. Today that is a literal text search over the bundled Quran and Hadith
// snapshot. A live provider (our Express backend with source-grounded retrieval) will
// implement the same interface and set `live: true`; no generated text is produced until then.
import { getJson } from "../../lib/apiClient";
import { isRecord, isString } from "../../lib/validation";

export type Citation = {
  kind: "quran" | "hadith";
  /** "Quran 2:153" or the Hadith title. */
  reference: string;
  arabic?: string;
  excerpt?: string;
  /** In-app route (Quran) or the source page (Hadith). */
  href: string;
  external: boolean;
};

export type AssistantReply =
  | { mode: "source-search"; query: string; citations: Citation[] }
  /** Reserved for the live assistant: generated text that must arrive with its sources. */
  | { mode: "generated"; text: string; citations: Citation[] };

export interface AssistantProvider {
  id: string;
  /** True only when answers are generated by a connected model. */
  live: boolean;
  ask(question: string, context: { language: string; signal?: AbortSignal }): Promise<AssistantReply>;
}

type SearchVerse = { surah: number; id: number; arabic: string; en: string; ur: string };
type SearchHadith = { id: number; title: string; urduTitle?: string; hadeeth: string; hadeeth_ar: string; urdu: string; source: string };

const fold = (text: string) =>
  text
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f\u064B-\u065F\u0670]/g, "")
    .replace(/[أإآ]/g, "ا");

let corpus: Promise<{ verses: SearchVerse[]; hadiths: SearchHadith[] }> | null = null;
function loadCorpus(signal?: AbortSignal) {
  corpus ??= Promise.all([getJson("/content/quran-search.json", { signal, timeoutMs: 60000 }), getJson("/content/hadiths.json", { signal, timeoutMs: 60000 })]).then(([verses, hadiths]) => ({
    verses: (Array.isArray(verses) ? verses : []).filter((v): v is SearchVerse => isRecord(v) && isString(v.arabic) && isString(v.en) && isString(v.ur)),
    hadiths: (Array.isArray(hadiths) ? hadiths : []).filter((h): h is SearchHadith => isRecord(h) && isString(h.title) && isString(h.hadeeth) && isString(h.source)),
  }));
  // A failed load must not be cached, or Retry could never succeed.
  corpus.catch(() => {
    corpus = null;
  });
  return corpus;
}

export const MIN_QUERY_LENGTH = 3;

export const sourceSearchProvider: AssistantProvider = {
  id: "bundled-source-search",
  live: false,
  async ask(question, { language, signal }) {
    const term = fold(question.trim());
    const { verses, hadiths } = await loadCorpus(signal);
    const citations: Citation[] = [];
    for (const v of verses) {
      if (citations.length >= 8) break;
      if (fold(`${v.arabic} ${v.en} ${v.ur}`).includes(term)) citations.push({ kind: "quran", reference: `Quran ${v.surah}:${v.id}`, arabic: v.arabic, excerpt: language === "ur" ? v.ur : language === "ar" ? undefined : v.en, href: `#/quran/${v.surah}?ayah=${v.id}`, external: false });
    }
    let count = 0;
    for (const h of hadiths) {
      if (count >= 5) break;
      if (fold(`${h.title} ${h.hadeeth} ${h.hadeeth_ar ?? ""} ${h.urdu ?? ""}`).includes(term)) {
        count++;
        citations.push({ kind: "hadith", reference: language === "ur" && h.urduTitle ? h.urduTitle : h.title, href: h.source, external: true });
      }
    }
    return { mode: "source-search", query: question.trim(), citations };
  },
};

export const assistantProvider: AssistantProvider = sourceSearchProvider;

export function askAssistant(question: string, context: { language: string; signal?: AbortSignal }) {
  return assistantProvider.ask(question, context);
}
